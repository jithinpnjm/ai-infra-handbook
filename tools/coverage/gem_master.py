#!/usr/bin/env python3
"""Merge the gem-book triage tables with a passage-level coverage measurement into one master map.
Output: planning/coverage/GEM_BOOKS_MASTER.md   Usage: python3 tools/coverage/gem_master.py
Reads planning/gem_books/*_triage.md (Gemini's triage), measures for each YES/PARTLY chapter how much of the book
text is NOT found in the handbook chapters named in its 'where it belongs' cell (same method as tools/book_passages.py),
and lists deferred rows from planning/gem_books/DEFERRED.md."""
import re, os, glob, sqlite3, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
db = sqlite3.connect(os.path.expanduser('~/Desktop/books-toon-rag/_index/chunks.db'))
word = re.compile(r"[A-Za-z][A-Za-z0-9_'-]{5,}|\d+(?:\.\d+)?|[\w./-]*[_/.][\w./-]+")
toks = lambda t: {w.lower().strip("'-") for w in word.findall(t)}
df = collections.Counter(); N = 0
for (c,) in db.execute('select content from chunks'):
    N += 1
    for w in toks(c): df[w] += 1
cache = {}
def hb_tokens(labels):
    out = set()
    for l in labels:
        if l not in cache:
            p, c = l.split('.'); s = ''
            for f in glob.glob(f'{ROOT}/docs/part-{int(p):02d}-*/{int(c):02d}-*.md'):
                t = open(f, errors='ignore').read(); i = t.find('## Sources and review notes'); s += t[:i if i > 0 else None]
            cache[l] = toks(s)
        out |= cache[l]
    return out
def paragraphs(text):
    paras, buf = [], []
    for line in text.split('\n'):
        if not line.strip(): continue
        buf.append(line.strip())
        if len(' '.join(buf).split()) >= 60 and re.search(r'[.!?:]$', line.strip()): paras.append(' '.join(buf)); buf = []
    if len(' '.join(buf).split()) >= 40: paras.append(' '.join(buf))
    return paras
def measure(book, chnum, labels):
    rows = db.execute('select content from chunks where book like ? and (chapter like ? or chapter like ? or chapter like ?) order by chunk_id',
                      (book[:60] + '%', f'{chnum}. %', f'Chapter {chnum}:%', f'Chapter {chnum} %')).fetchall()
    if not rows or not labels: return None
    hbt = hb_tokens(labels); tot = miss = 0
    for p in paragraphs('\n'.join(r[0] for r in rows)):
        ts = {w for w in toks(p) if df[w] <= max(3, 0.02 * N)}
        if len(ts) < 6: continue
        w = len(p.split()); tot += w
        if len(ts & hbt) / len(ts) < 0.35: miss += w
    return None if tot == 0 else miss / tot
out = ['# Gem books master map (generated)', '',
       'Generated by `tools/coverage/gem_master.py` from `planning/gem_books/*_triage.md` and the passage-level check in `tools/book_passages.py`. '
       'Re-run after Gemini changes a triage file or a chapter. "Not found" is the share of the book chapter\'s checked text whose distinctive terms are missing from the target handbook chapters: '
       '0 to 15 percent means well covered, 15 to 40 percent partly covered, above 40 percent means the explanations are mostly missing (the status FULL in a triage file is not trusted when this number is high). '
       'Per-heading coverage tables for each handbook chapter are in `planning/coverage/chapters/`; per-book heading maps are in `planning/coverage/maps/`.', '']
for tf in sorted(glob.glob(f'{ROOT}/planning/gem_books/*_triage.md')):
    base = os.path.basename(tf).replace('_triage.md', '')
    book = base
    out += [f'## {book}', '', '| Book chapter | Relevant | Target handbook chapter(s) | Triage status | Not found in handbook (checked text) |', '|---|---|---|---|---|']
    for line in open(tf):
        if not line.startswith('| ') or line.startswith('| Book chapter') or line.startswith('|---'): continue
        c = [x.strip() for x in line.strip().strip('|').split('|')]
        if len(c) < 5: continue
        m = re.match(r'^(?:Chapter\s+)?(\d+)[.: ]', c[0])
        labels = sorted(set(re.findall(r'\b(\d{1,2}\.\d{1,2})\b', c[3])))
        labels = [l for l in labels if len(hb_tokens([l])) > 500]   # only written chapters (scaffold stubs are tiny)
        st = c[4].split('(')[0].strip()[:8]
        pct = '-' if not (m and labels and c[1].startswith(('YES', 'PARTLY'))) else None
        if pct is None:
            r = measure(book, int(m.group(1)), labels); pct = 'n/a' if r is None else f'{r:.0%}'
        out.append(f'| {c[0][:70]} | {c[1]} | {c[3][:70]} | {st} | {pct} |')
    out.append('')
open(f'{ROOT}/planning/coverage/GEM_BOOKS_MASTER.md', 'w').write('\n'.join(out) + '\n')
print('written', len(out), 'lines')
