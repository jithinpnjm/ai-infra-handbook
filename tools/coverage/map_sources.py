#!/usr/bin/env python3
"""Audit: for each source book, which handbook chapters cite each source chapter? Lists UNMAPPED source chapters.
Reads planning/structure.txt (sources fields) and planning/source-outlines/<slug>.md. Writes planning/coverage/maps/<slug>.md and planning/coverage/MASTER_MAP.md"""
import os, re, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CODES = {"HLW": "how-linux-works-3rd-edition", "SP": "systems-performance-2nd-edition", "CN": "computer-networking-problems-and-solutions",
 "NPA": "network-programmability-and-automation-2nd-edition", "NK": "networking-and-kubernetes", "KUR": "kubernetes-up-and-running-3rd-edition",
 "PK": "production-kubernetes", "AUR": "ansible-up-and-running-3rd-edition", "TUR": "terraform-up-and-running-3rd-edition",
 "LP": "learning-python-6th-edition", "FP": "fluent-python-2nd-edition", "FA": "building-python-web-apis-with-fastapi",
 "SCL": "supercomputers-for-linux-sysadmins-managing-modern-hpc-clusters-and-supercomputers-from-software-to",
 "ASP": "ai-systems-performance-engineering", "ADC": "ai-data-center-network-design-and-technologies", "DAI": "distributed-ai-systems",
 "HLS": "hands-on-llm-serving-and-optimization", "AIE": "ai-engineering", "DMLS": "designing-machine-learning-systems",
 "EAS": "engineering-ai-systems-architecture-and-devops-essentials", "LEH": "llm-engineers-handbook", "LLO": "llmops", "PM": "practical-mlops",
 "GAK": "generative-ai-on-kubernetes", "AF": "ai-factory", "ANC": "ai-networking-cookbook",
 "KPG": "kubernetes-programming-with-go-programming-kubernetes-clients-and-operators-using-go-and-the-kuberne",
 "MLPE": "machine-learning-platform-engineering", "PHPC": "parallel-and-high-performance-computing", "K8GS": "kubernetes-for-generative-ai-solutions",
 "LLP": "llms-in-production", "SKI": "scalable-kubernetes-infrastructure-for-ai-platforms"}
SKIP = re.compile(r"^(preface|foreword|index|glossary|about|acknowledg|colophon|copyright|dedication|praise|bibliography|references|contents|table of contents|introduction$|epilogue|afterword|appendix [b-z]|summary of changes|front matter|cover|title)", re.I)

def expand(txt):
    out = set()
    for part in re.split(r"\s*,\s*", txt):
        m = re.match(r"^(\d+)-(\d+)$", part)
        if m: out.update(range(int(m.group(1)), int(m.group(2)) + 1))
        elif part.isdigit(): out.add(int(part))
    return out

# handbook citations
cites = collections.defaultdict(lambda: collections.defaultdict(set))   # code -> source chapter number -> handbook ids
whole = collections.defaultdict(set)                                    # code -> handbook ids citing the book without numbers
part = None
for raw in open(os.path.join(ROOT, "planning", "structure.txt"), encoding="utf-8"):
    line = raw.strip()
    if line.startswith("@PART"): part = int(line.split("|")[0].split()[1]); continue
    m = re.match(r"^(\d\d) \| ([^|]*)\|[^|]*\| ([^|]*)", line)
    if not m: continue
    hid = f"{part}.{int(m.group(1))}"; srcs = m.group(3)
    for code in CODES:
        for mm in re.finditer(rf"\b{code}\s+((?:\d+(?:-\d+)?)(?:\s*,\s*\d+(?:-\d+)?)*)", srcs):
            for n in expand(mm.group(1)): cites[code][n].add(hid)
        if re.search(rf"\b{code}\b(?!\s*\d)", srcs): whole[code].add(hid)

skips = {}
sp = os.path.join(ROOT, "planning", "coverage", "skips.txt")
if os.path.exists(sp):
    for l in open(sp, encoding="utf-8"):
        m = re.match(r"^([A-Z0-9]+) (\d+) \| (.*)$", l.strip())
        if m: skips[(m.group(1), int(m.group(2)))] = m.group(3)
master = ["# Master map: source chapters not cited by any handbook chapter", "",
          "Generated by tools/coverage/map_sources.py. A source chapter listed here has **no handbook chapter assigned**. Either add it to a chapter's Sources in `structure.txt`, or decide it is skipped (and say why in that book's map).", ""]
for code, slug in CODES.items():
    path = os.path.join(ROOT, "planning", "source-outlines", slug + ".md")
    if not os.path.exists(path): continue
    chapters = []
    import glob
    toons = glob.glob(os.path.expanduser(f"~/Desktop/books-toon-rag/{slug}/*.toon"))
    if toons:
        txt = open(toons[0], encoding="utf-8").read()
        for blk in re.split(r"\n  - index: ", txt)[1:]:
            tt = re.search(r"\n    title: (.*)", blk); wc = re.search(r"\n    word_count: (\d+)", blk)
            if not tt or not wc or int(wc.group(1)) < 600: continue
            t = tt.group(1).strip().strip('"'); m = re.match(r"^(?:chapter|ch\.?)?\s*(\d+)(?:[\.\:\s\-]|$)", t, re.I)
            if m: chapters.append((int(m.group(1)), t))
    seen = {}
    for n, t in chapters:
        if n not in seen or len(t) > len(seen[n]): seen[n] = t
    rows, unmapped = [], []
    for n in sorted(seen):
        ids = sorted(cites[code].get(n, set()) | set(), key=lambda x: [int(p) for p in x.split(".")])
        if not ids and (code, n) in skips:
            rows.append(f"| {n} | {seen[n][:70].replace('|','/')} | SKIPPED: {skips[(code, n)]} |"); continue
        whole_ids = sorted(whole[code], key=lambda x: [int(p) for p in x.split(".")])
        if not ids and whole_ids and not cites[code]:
            rows.append(f"| {n} | {seen[n][:70].replace('|','/')} | whole-book citation: {', '.join(whole_ids)} (assign chapters when writing) |")
            continue
        rows.append(f"| {n} | {seen[n][:70].replace('|','/')} | {', '.join(ids) if ids else '**UNMAPPED**'} |")
        if not ids and not SKIP.match(seen[n]): unmapped.append(f"{n}. {seen[n][:70]}")
    out = [f"# Source map: {slug}", "", f"Code `{code}`. Whole-book citations (no chapter numbers): {', '.join(sorted(whole[code])) or 'none'}.", "",
           "| # | Source chapter | Handbook chapters citing it |", "|---|---|---|"] + rows
    open(os.path.join(ROOT, "planning", "coverage", "maps", slug + ".md"), "w").write("\n".join(out) + "\n")
    if unmapped: master += [f"## {code}: {slug}", ""] + [f"- {u}" for u in unmapped] + [""]
    print(f"{code:5} chapters={len(seen):3} unmapped={len(unmapped)}")
open(os.path.join(ROOT, "planning", "coverage", "MASTER_MAP.md"), "w").write("\n".join(master) + "\n")
