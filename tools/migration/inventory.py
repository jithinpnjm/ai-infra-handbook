#!/usr/bin/env python3
"""Inventory every file of the author's nvidia-devops docs and map it to handbook chapters (via the Sources fields in planning/structure.txt).
Status becomes 'migrated' when a handbook chapter's text mentions the file's basename (put a line 'Migrated from nvidia-devops: <file names>' in the chapter's Sources section).
Writes planning/MIGRATION_MAP.md. Usage: python3 tools/migration/inventory.py"""
import glob, os, re, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.expanduser(os.environ.get("NVIDIA_DEVOPS_DOCS", "~/Documents/GitHub/nvidia-devops/docs"))

def vol_code(rel):
    p = rel.split(os.sep)
    if p[0] == "nvidia-zero-to-hero":
        m = re.match(r"volume-(\d+)", p[1]); return f"V{int(m.group(1))}" if m else "VINTRO"
    if re.match(r"volume-\d+", p[0]): return f"VL{int(re.match(r'volume-(\d+)', p[0]).group(1))}"
    if p[0] == "core-interview-questions": return "VCORE"
    if p[0] == "intro": return "VINTRO"
    if p[0] == "nvidia-zero-to-hero" and len(p) == 2: return "VINTRO"
    return None

# handbook citations: (code, chapter or None) -> handbook ids
cites = collections.defaultdict(set); part = None
for raw in open(os.path.join(ROOT, "planning", "structure.txt"), encoding="utf-8"):
    line = raw.strip()
    if line.startswith("@PART"): part = int(line.split("|")[0].split()[1]); continue
    m = re.match(r"^(\d\d) \| ([^|]*)\|[^|]*\| ([^|]*)", line)
    if not m: continue
    hid = f"{part}.{int(m.group(1))}"
    for mm in re.finditer(r"\b(V\d+|VL\d+|VCORE|VINTRO)\b(?:\s+(?:ch(\d+(?:\s*,\s*\d+|-\d+)*)|P(\d+)))?", m.group(3)):
        code, chs, proj = mm.group(1), mm.group(2), mm.group(3)
        if chs:
            for part_ in re.split(r"\s*,\s*", chs):
                r = re.match(r"^(\d+)-(\d+)$", part_)
                nums = range(int(r.group(1)), int(r.group(2)) + 1) if r else [int(part_)]
                for n in nums: cites[(code, n)].add(hid)
        elif proj: cites[(code, "P" + proj)].add(hid)
        else: cites[(code, None)].add(hid)

# text of written chapters, to detect migration
written = ""
for f in glob.glob(os.path.join(ROOT, "docs", "part-*", "*.md")):
    t = open(f, encoding="utf-8").read()
    if not re.search(r'status:\s*"?scaffold"?', t[:600]): written += "\n" + t

files = sorted(glob.glob(os.path.join(SRC, "**", "*.md"), recursive=True) + glob.glob(os.path.join(SRC, "**", "*.mdx"), recursive=True))
by_vol = collections.OrderedDict(); unmapped = []; total_words = 0; migrated_words = 0
for f in files:
    rel = os.path.relpath(f, SRC); code = vol_code(rel)
    txt = open(f, encoding="utf-8", errors="ignore").read(); words = len(txt.split()); total_words += words
    title = (re.search(r"^title:\s*[\"']?(.*?)[\"']?\s*$", txt, re.M) or re.search(r"^#\s+(.*)$", txt, re.M) or [None, os.path.basename(f)])[1][:70]
    base = os.path.basename(f); n = None
    m = re.match(r"^(?:chapter-)?(\d+)", base)
    if m and "lab" not in base[:4]: n = int(m.group(1))
    ids = set()
    if n is not None: ids |= cites.get((code, n), set())
    ids |= cites.get((code, None), set())
    pm = re.search(r"project-?(\d+)", base)                    # capstone projects
    if pm: ids |= cites.get((code, "P" + pm.group(1)), set())
    # volume-level fallbacks for labs/index/summary/projects not individually cited
    if not ids:
        for (c, k), v in cites.items():
            if c == code: ids |= v
    stem = os.path.splitext(base)[0]
    part_mig = bool(re.search(re.escape(base) + r"`?\s*\(partial", written)) or bool(re.search(re.escape(stem) + r"\S*\s*\(partial", written))
    mig = (base in written or stem in written) and not part_mig
    if mig: migrated_words += words
    key = code or "OTHER"
    by_vol.setdefault(key, []).append((rel, words, title, sorted(ids, key=lambda x: [int(p) for p in x.split(".")]), mig, part_mig))
    if not ids: unmapped.append(rel)

out = ["# Migration map: nvidia-devops docs into the handbook", "",
       f"Goal: every piece of the author's existing repo lives in the handbook so that `nvidia-devops` can be archived. Generated by `tools/migration/inventory.py`.",
       f"Files: {len(files)}; words: {total_words:,}; migrated so far: {migrated_words:,} words ({100*migrated_words/max(total_words,1):.1f}%). Unmapped files: {len(unmapped)}.", "",
       "**How to migrate a file:** when writing handbook chapter X, read every nvidia-devops file listed against X here, reuse and adapt the content (your own work: reuse diagrams, labs, tables, interview Q&A directly), unify style, remove duplication, raise depth to the book's standard, fix errors, and add a line `Migrated from nvidia-devops: <file names>` in the chapter's Sources section. Rerun the tool to update this table.", ""]
for code, rows in by_vol.items():
    w = sum(r[1] for r in rows); mw = sum(r[1] for r in rows if r[4])
    out += [f"## {code}: {len(rows)} files, {w:,} words ({mw:,} migrated)", "", "| File | Words | Title | Handbook chapters | Migrated |", "|---|---|---|---|---|"]
    for rel, words, title, ids, mig, part_mig in rows:
        out.append(f"| {rel} | {words} | {title.replace('|','/')} | {', '.join(ids) or '**UNMAPPED**'} | {'yes' if mig else ('partial' if part_mig else '')} |")
    out.append("")
open(os.path.join(ROOT, "planning", "MIGRATION_MAP.md"), "w", encoding="utf-8").write("\n".join(out))
print(f"{len(files)} files, {total_words:,} words, unmapped {len(unmapped)}")
for u in unmapped[:40]: print("  UNMAPPED:", u)
