#!/usr/bin/env python3
"""Generate dnsmasq DHCP/TFTP configuration and per-node iPXE scripts from an inventory CSV, with validation.

CSV columns: name,mac,ip,bmc_mac,bmc_ip,role,image
Usage: gen_provision.py inventory.csv OUTDIR [--subnet 10.10.0.0/16] [--bmc-subnet 10.20.0.0/16]
        [--server 10.10.0.1] [--http http://10.10.0.1:8080]
Syntax follows dnsmasq(8): dhcp-range, dhcp-host, dhcp-match, dhcp-boot, enable-tftp, tftp-root.
"""
import argparse
import csv
import ipaddress
import os
import re
import sys


def validate(rows, subnet, bmc_subnet):
    errs, seen = [], {}
    for r in rows:
        if not re.fullmatch(r"[a-z][a-z0-9-]*", r["name"]):
            errs.append(f"{r['name']}: invalid hostname")
        for field, net in (("ip", subnet), ("bmc_ip", bmc_subnet)):
            try:
                if ipaddress.ip_address(r[field]) not in net:
                    errs.append(f"{r['name']}: {field} {r[field]} not in {net}")
            except ValueError:
                errs.append(f"{r['name']}: bad {field} {r[field]!r}")
        for field in ("mac", "bmc_mac"):
            r[field] = r[field].lower()
            if not re.fullmatch(r"([0-9a-f]{2}:){5}[0-9a-f]{2}", r[field]):
                errs.append(f"{r['name']}: bad {field} {r[field]!r}")
        for field in ("name", "mac", "ip", "bmc_mac", "bmc_ip"):
            key = (field if field == "name" else "addr", r[field])
            if key in seen:
                errs.append(f"duplicate {field} {r[field]} ({seen[key]} and {r['name']})")
            seen[key] = r["name"]
    return errs


def dnsmasq_conf(rows, subnet, bmc_subnet, server, http):
    L = ["# generated by gen_provision.py: do not edit by hand",
         "# DHCP+TFTP only; DNS is served elsewhere","port=0",
         "enable-tftp", "tftp-root=/srv/tftp",
         "dhcp-authoritative",
         "# discovery pools for unknown machines",
         f"dhcp-range={subnet.network_address + 1000},{subnet.network_address + 1999},{subnet.netmask},1h",
         f"dhcp-range={bmc_subnet.network_address + 1000},{bmc_subnet.network_address + 1999},{bmc_subnet.netmask},1h",
         "# identify the client firmware",
         "dhcp-match=set:ipxe,175",
         "dhcp-match=set:efi64,option:client-arch,7",
         "dhcp-match=set:efi64,option:client-arch,9",
         "# chain-load iPXE first; once iPXE runs (option 175) hand it an HTTP script",
         "dhcp-boot=tag:!ipxe,tag:efi64,ipxe.efi",
         "dhcp-boot=tag:!ipxe,tag:!efi64,undionly.kpxe",
         f"dhcp-boot=tag:ipxe,{http}/boot.ipxe",
         f"dhcp-option=option:router,{server}",
         "log-dhcp"]
    for r in rows:
        L.append(f"dhcp-host={r['mac']},{r['name']},{r['ip']},set:{r['role']}")
        L.append(f"dhcp-host={r['bmc_mac']},{r['name']}-bmc,{r['bmc_ip']}")
    return "\n".join(L) + "\n"


def ipxe_node(r, http):
    return "\n".join([
        "#!ipxe", f"# {r['name']} role={r['role']} image={r['image']}",
        "dhcp",
        f"kernel {http}/images/{r['image']}/vmlinuz ip=dhcp root=live:{http}/images/{r['image']}/rootfs.squashfs rd.live.image hostname={r['name']} console=ttyS0,115200",
        f"initrd {http}/images/{r['image']}/initrd.img",
        "boot || goto failed", ":failed", "echo boot failed; sleep 10; reboot", ""])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("outdir")
    ap.add_argument("--subnet", default="10.10.0.0/16")
    ap.add_argument("--bmc-subnet", default="10.20.0.0/16")
    ap.add_argument("--server", default="10.10.0.1")
    ap.add_argument("--http", default="http://10.10.0.1:8080")
    a = ap.parse_args()
    subnet, bmc = ipaddress.ip_network(a.subnet), ipaddress.ip_network(a.bmc_subnet)
    rows = list(csv.DictReader(open(a.csv)))
    errs = validate(rows, subnet, bmc)
    if errs:
        print("\n".join("ERROR " + e for e in errs))
        sys.exit(1)
    os.makedirs(os.path.join(a.outdir, "ipxe"), exist_ok=True)
    open(os.path.join(a.outdir, "dnsmasq.conf"), "w").write(dnsmasq_conf(rows, subnet, bmc, a.server, a.http))
    for r in rows:
        open(os.path.join(a.outdir, "ipxe", f"{r['name']}.ipxe"), "w").write(ipxe_node(r, a.http))
    open(os.path.join(a.outdir, "ipxe", "boot.ipxe"), "w").write(
        "#!ipxe\ndhcp\nchain " + a.http + "/ipxe/${hostname}.ipxe || chain " + a.http + "/ipxe/${mac:hexhyp}.ipxe || goto discovery\n:discovery\necho unknown node; chain " + a.http + "/ipxe/discovery.ipxe\n")
    print(f"wrote dnsmasq.conf and {len(rows)} iPXE scripts to {a.outdir}")


if __name__ == "__main__":
    main()
